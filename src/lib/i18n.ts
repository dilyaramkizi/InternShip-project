import { useNavigate, useSearch } from "@tanstack/react-router";

export type Lang = "en" | "ru";
export const parseLang = (value: unknown): Lang => (value === "ru" ? "ru" : "en");

/** Reads `?lang=` from the URL. The root route retains it across every navigation. */
export function useLang(): Lang {
  return useSearch({ strict: false, select: (s: { lang?: unknown }) => parseLang(s.lang) });
}

export function useSetLang() {
  const navigate = useNavigate();
  return (lang: Lang) =>
    void navigate({
      to: ".",
      search: ((prev: Record<string, unknown>) => ({ ...prev, lang })) as never,
      replace: true,
      resetScroll: false,
    });
}

